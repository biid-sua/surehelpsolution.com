<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\Artisan;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;

/**
 * Writes docs/schema.md from the migrations, so the schema reference can't drift from the code. It
 * migrates a temporary in-memory SQLite database, so the result is the same on every machine,
 * whatever database a developer uses. `--check` fails when the file is out of date (SchemaDocsTest).
 */
class SchemaDocs extends Command
{
    protected $signature = 'docs:schema {--check : Fail if docs/schema.md is out of date instead of writing it}';

    protected $description = 'Generate docs/schema.md (every table, column, key and index) from the migrations';

    private const CONNECTION = 'schema_docs';

    public function handle(): int
    {
        $markdown = $this->generate();
        $path = base_path('docs/schema.md');

        if ($this->option('check')) {
            if (! is_file($path) || file_get_contents($path) !== $markdown) {
                $this->error('docs/schema.md is out of date. Run: php artisan docs:schema');

                return self::FAILURE;
            }
            $this->info('docs/schema.md is up to date.');

            return self::SUCCESS;
        }

        file_put_contents($path, $markdown);
        $this->info('Wrote docs/schema.md.');

        return self::SUCCESS;
    }

    public function generate(): string
    {
        $default = config('database.default');
        $cache = [config('cache.default'), config('permission.cache.store')];
        // Migrations also clear caches; keep that away from the developer's real stores.
        config(['cache.default' => 'array', 'permission.cache.store' => 'array']);
        config(['database.connections.'.self::CONNECTION => ['driver' => 'sqlite', 'database' => ':memory:', 'prefix' => '', 'foreign_key_constraints' => true]]);
        DB::purge(self::CONNECTION);
        try {
            Artisan::call('migrate', ['--database' => self::CONNECTION, '--force' => true]);
            $schema = Schema::connection(self::CONNECTION);
            $tables = collect($schema->getTableListing(schemaQualified: false))->reject(fn ($t) => $t === 'migrations')->sort()->values();

            $out = [
                '# Database schema',
                '',
                '_Generated by `php artisan docs:schema` from the migrations. Don\'t edit it by hand: change a migration, then run the command. A test fails while this file is out of date._',
                '',
                'Types are as SQLite reports them (production runs MySQL/MariaDB: `tinyint(1)` is a boolean, `text` may be JSON). Business data carries `organization_id` and is scoped to the current business (see [permissions.md](permissions.md)).',
                '',
                '**'.$tables->count().' tables.** '.$tables->map(fn ($t) => "[{$t}](#{$t})")->implode(' · '),
                '',
            ];
            foreach ($tables as $table) {
                $columns = $schema->getColumns($table);
                $indexes = $schema->getIndexes($table);
                $primary = collect($indexes)->firstWhere('primary', true)['columns'] ?? [];
                $foreign = collect($schema->getForeignKeys($table))
                    ->filter(fn ($fk) => count($fk['columns']) === 1)
                    ->mapWithKeys(fn ($fk) => [$fk['columns'][0] => $fk['foreign_table'].'.'.$fk['foreign_columns'][0].($fk['on_delete'] && $fk['on_delete'] !== 'no action' ? ' ('.strtolower($fk['on_delete']).')' : '')]);
                $unique = collect($indexes)->filter(fn ($i) => $i['unique'] && ! $i['primary'] && count($i['columns']) === 1)->map(fn ($i) => $i['columns'][0])->flip();

                $out[] = "## {$table}";
                $out[] = '';
                $out[] = '| Column | Type | Null | Default | Notes |';
                $out[] = '|---|---|---|---|---|';
                foreach ($columns as $c) {
                    $notes = array_filter([
                        in_array($c['name'], $primary, true) ? 'primary key' : null,
                        isset($foreign[$c['name']]) ? '→ '.$foreign[$c['name']] : null,
                        isset($unique[$c['name']]) ? 'unique' : null,
                    ]);
                    $default = $c['default'] === null ? '' : '`'.str_replace('|', '\|', trim((string) $c['default'], "'\"")).'`';
                    $out[] = sprintf('| `%s` | %s | %s | %s | %s |', $c['name'], $c['type'], $c['nullable'] ? 'yes' : '', $default, implode(', ', $notes));
                }
                $multi = collect($indexes)->filter(fn ($i) => ! $i['primary'] && count($i['columns']) > 1)
                    ->map(fn ($i) => ($i['unique'] ? 'unique ' : '').'('.implode(', ', $i['columns']).')')->sort()->values();
                if (count($primary) > 1) {
                    $multi->prepend('primary key ('.implode(', ', $primary).')');
                }
                if ($multi->isNotEmpty()) {
                    $out[] = '';
                    $out[] = 'Indexes: '.$multi->implode('; ').'.';
                }
                $out[] = '';
            }

            return implode("\n", $out);
        } finally {
            DB::disconnect(self::CONNECTION);
            config(['database.default' => $default, 'cache.default' => $cache[0], 'permission.cache.store' => $cache[1]]);
        }
    }
}
